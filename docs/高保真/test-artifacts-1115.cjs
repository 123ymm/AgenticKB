// Standalone prototype checks. Requires Playwright; application code is not used.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
let browser;

(async () => {
  const launch = { headless: true };
  if (process.env.PROTOTYPE_BROWSER_PATH) launch.executablePath = process.env.PROTOTYPE_BROWSER_PATH;
  else if (process.platform === 'win32' && fs.existsSync('C:/Program Files/Google/Chrome/Application/chrome.exe')) launch.channel = 'chrome';
  browser = await chromium.launch(launch);
  const page = await browser.newPage({ viewport: { width: 1100, height: 1250 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setContent(fs.readFileSync(path.join(__dirname, 'artifacts-1115.html'), 'utf8'));
  const f = page.frameLocator('iframe');
  const action = name => f.locator(`[data-a="${name}"]`);
  await f.locator('.ar-list-table').waitFor();
  assert.equal(await f.locator('.ar-list-table tbody tr').count(), 3);
  await f.locator('.ar-name[data-id="wiki-pool"]').click();
  await f.locator('[data-a="wiki-mode"][data-mode="graph"]').click();
  assert.equal(await f.locator('.ar-graph-node').count(), 3);
  assert.equal(await f.locator('.ar-graph-edge').count(), 6);
  await f.locator('.ar-graph-node[data-key="pool-feature"]').click();
  assert.match(await f.locator('.ar-graph-context h3').innerText(), /资源池管理特性/);
  await action('graph-open').click();
  assert.match(await f.locator('.ar-md h1').innerText(), /资源池管理特性/);
  await f.locator('.ar-page-link[data-key="add-pool"]').click();
  await action('page-properties').click();
  await f.locator('#ar-page-aliases').fill('pool-feature');
  await action('page-properties-confirm').click();
  await action('edit-md').click();
  const body = await f.locator('#ar-md').inputValue();
  await f.locator('#ar-md').fill(body + '\n\n[[资源池特性]]\n\n[[missing-page]]');
  await f.locator('[data-a="wiki-mode"][data-mode="graph"]').click();
  assert.match(await f.locator('[role="dialog"]').innerText(), /尚未保存/);
  await action('close').first().click();
  await action('save-md').click();
  await f.locator('[data-a="wiki-mode"][data-mode="graph"]').click();
  assert.equal(await f.locator('.ar-graph-node').count(), 4);
  assert.equal(await f.locator('.ar-graph-edge').count(), 7);
  assert.equal(await f.locator('.ar-graph-node.ghost').count(), 1);
  assert.equal(await f.locator('.ar-graph-edge.broken').count(), 1);
  await f.locator('.ar-graph-node[data-key="missing-page"]').click();
  await f.locator('#ar-graph-scope').selectOption('neighbors');
  assert.equal(await f.locator('.ar-graph-node').count(), 2);
  await f.locator('#ar-graph-scope').selectOption('all');
  await f.locator('#ar-graph-search').fill('missing');
  assert.equal(await f.locator('.ar-graph-node').count(), 1);
  await f.locator('#ar-graph-search').fill('');
  await f.locator('.ar-tabs [data-tab="runtime"]').click();
  assert.equal(await f.locator('.ar-graph-node').count(), 3);
  assert.equal(await f.locator('.ar-graph-node.ghost').count(), 0);
  await f.locator('#ar-user').selectOption('王工');
  assert.equal(await f.locator('.ar-tabs [data-tab="design"]').isDisabled(), true);
  await f.locator('.ar-graph-node[data-key="add-pool"]').click();
  await action('graph-open').click();
  assert.equal(await action('edit-md').count(), 0);
  await f.locator('[data-a="wiki-mode"][data-mode="graph"]').click();
  if (process.env.PROTOTYPE_SCREENSHOT) await page.screenshot({ path: process.env.PROTOTYPE_SCREENSHOT, fullPage: true });
  await page.setViewportSize({ width: 390, height: 1100 });
  assert.equal(await page.frames()[1].evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1), false);
  await f.locator('.ar-graph-node[data-key="pool-guide"]').click();
  await action('graph-open').click();
  assert.match(await f.locator('.ar-md h1').innerText(), /资源池配置步骤/);
  assert.deepEqual(errors, []);
  console.log('PASS: Wiki graph/read switching, node navigation, draft isolation, broken links, search, one-hop, role and responsive checks');
  await browser.close();
})().catch(async error => {
  console.error(error);
  if (browser) await browser.close();
  process.exitCode = 1;
});
